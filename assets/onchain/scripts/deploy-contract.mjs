#!/usr/bin/env node
// Deploy a Foundry-built contract and record its address and ABI for the frontend.
// usage: node scripts/deploy-contract.mjs <Name | File.sol:Name> ['[constructor, args, as, JSON]']
// env:   RPC_URL (default http://127.0.0.1:8545); DEPLOYER_PRIVATE_KEY (funded; optional only on anvil, chain 31337)
// Writes contracts/deployments.json (source of truth) and regenerates lib/contracts.ts (typed, as const).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createPublicClient, createWalletClient, http } from "viem";
import { privateKeyToAccount } from "viem/accounts";

const [target, argsJson = "[]"] = process.argv.slice(2);
if (!target) {
  console.error("Usage: node scripts/deploy-contract.mjs <Name | File.sol:Name> ['[constructor args JSON]']");
  process.exit(1);
}
const [file, name] = target.includes(":") ? target.split(":") : [`${target}.sol`, target];
const artifactPath = `contracts/out/${file}/${name}.json`;
if (!existsSync(artifactPath)) {
  console.error(`No artifact at ${artifactPath}. Run npm run contracts:build first.`);
  process.exit(1);
}
const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));

const rpc = process.env.RPC_URL || "http://127.0.0.1:8545";
const publicClient = createPublicClient({ transport: http(rpc) });
const chainId = await publicClient.getChainId();
// Anvil's well-known, publicly documented development account 0. Never used on any other chain.
const ANVIL_KEY = "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80";
const key = process.env.DEPLOYER_PRIVATE_KEY || (chainId === 31337 ? ANVIL_KEY : undefined);
if (!key) {
  console.error(`Chain ${chainId} needs DEPLOYER_PRIVATE_KEY: a key the owner controls, funded for gas on that chain.`);
  process.exit(1);
}
const account = privateKeyToAccount(key);
const balance = await publicClient.getBalance({ address: account.address });
if (balance === 0n) {
  console.error(`Deployer ${account.address} has no funds on chain ${chainId}. The owner must fund it; nothing was sent.`);
  process.exit(1);
}

const wallet = createWalletClient({ account, transport: http(rpc) });
const hash = await wallet.deployContract({ abi: artifact.abi, bytecode: artifact.bytecode.object, args: JSON.parse(argsJson), chain: null });
const receipt = await publicClient.waitForTransactionReceipt({ hash });
if (receipt.status !== "success" || !receipt.contractAddress) {
  console.error(`Deployment transaction ${hash} failed.`);
  process.exit(1);
}

const store = "contracts/deployments.json";
const deployments = existsSync(store) ? JSON.parse(readFileSync(store, "utf8")) : {};
deployments[chainId] = { ...deployments[chainId], [name]: { address: receipt.contractAddress, abi: artifact.abi, blockNumber: Number(receipt.blockNumber), txHash: hash } };
writeFileSync(store, `${JSON.stringify(deployments, null, 2)}\n`);
writeFileSync(
  "lib/contracts.ts",
  `// Generated by scripts/deploy-contract.mjs from contracts/deployments.json. Do not edit by hand.\nexport const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`,
);
console.log(`${name} deployed at ${receipt.contractAddress} on chain ${chainId} (tx ${hash}). Updated lib/contracts.ts.`);
if (chainId !== 31337) console.log(`Verify: forge verify-contract ${receipt.contractAddress} src/${file}:${name} --root contracts --chain ${chainId} --watch (needs ETHERSCAN_API_KEY)`);
